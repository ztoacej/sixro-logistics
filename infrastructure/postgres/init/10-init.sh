#!/usr/bin/env bash
set -Eeuo pipefail
psql_cmd=(psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1)
"${psql_cmd[@]}" <<'SQL'
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
SQL
for service in user company product order inventory delivery hub notification; do
  "${psql_cmd[@]}" --set role_name="${service}_user" --set schema_name="${service}_schema" \
    --set app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE :"role_name" LOGIN PASSWORD :'app_password';
CREATE SCHEMA :"schema_name" AUTHORIZATION :"role_name";
REVOKE ALL ON SCHEMA :"schema_name" FROM PUBLIC;
GRANT CONNECT ON DATABASE sixro_db TO :"role_name";
ALTER ROLE :"role_name" IN DATABASE sixro_db SET search_path TO :"schema_name", public;
SQL
done
# Reuse existing table definitions. Notification is generated by local Hibernate
# because its legacy enum DDL differs from the current @Enumerated mapping.
for sql in \
  /service-ddl/user/01_create_user_tables.sql \
  /service-ddl/company/01_create_company_tables.sql \
  /service-ddl/product/01_create_product_tables.sql \
  /service-ddl/order/01.create_order_tables.sql \
  /service-ddl/inventory/01.create_inventory_tables.sql \
  /service-ddl/delivery/01_create_delivery_tables.sql; do
  "${psql_cmd[@]}" --file "$sql"
done
# The Hub dump includes tables and local reference data. The schema exists above.
tr -d '\r' < /service-ddl/hub/00_init_hub_schema_and_data.sql \
  | sed '/^CREATE SCHEMA hub_schema;$/d' \
  | "${psql_cmd[@]}"
# Some legacy SQL/dump objects are owned by postgres. Transfer ownership so each
# app can perform local Hibernate schema updates using its own account.
for service in user company product order inventory delivery hub notification; do
  "${psql_cmd[@]}" --set role_name="${service}_user" --set schema_name="${service}_schema" <<'SQL'
SELECT format('ALTER TABLE %I.%I OWNER TO %I', schemaname, tablename, :'role_name')
FROM pg_tables WHERE schemaname = :'schema_name' \gexec
GRANT USAGE, CREATE ON SCHEMA :"schema_name" TO :"role_name";
GRANT ALL ON ALL SEQUENCES IN SCHEMA :"schema_name" TO :"role_name";
SQL
done
# Used by healthcheck: accept connections only after the complete init succeeded.
"${psql_cmd[@]}" -c 'CREATE TABLE public.local_init_complete (id integer PRIMARY KEY); INSERT INTO public.local_init_complete VALUES (1);'
